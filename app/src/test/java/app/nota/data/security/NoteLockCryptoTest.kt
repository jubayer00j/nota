/**
 * Per-note lock crypto tests (Phase 2b) — the centrepiece is a set of
 * CROSS-IMPLEMENTATION known-answer fixtures: the constants below were
 * generated by an INDEPENDENT tool (a single-file Java program using
 * only raw JCE — SecretKeyFactory PBKDF2 + Cipher AES-GCM — written
 * directly from the parameters in 1.x's shipped `note-lock-crypto.ts`
 * and `app-lock-crypto.ts`; it shares no code with the implementation
 * under test, and Python `cryptography` was unavailable in the build
 * environment, hence raw JCE as the independent route).
 *
 * Fixture parameters: NEK = bytes 0x00..0x1f; content IV = 0xa0..0xab;
 * attachment IV = 0xb0..0xbb; slot salts are the 16 ASCII bytes noted
 * per method; slot wrap IVs = 0xc0../0xd0../0xe0... Test-only secrets:
 * password "correct horse fixture" (600k), PIN "135790" (300k,
 * canonical "noma_pin_v1:135790"), pattern [0,1,2,5,8] (100k,
 * canonical "noma_pattern_v1:0-1-2-5-8").
 */
class NoteLockCryptoTest {

    private val nek: ByteArray = HexFormat.of().parseHex("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f")
    private val fixtureHtml = "<p>Hello fixture world</p>"
    private val fixtureDataUrl = "data:text/plain;base64,SGVsbG8gYXR0YWNobWVudA=="
    private val contentEnvelope = """{"nomaEnc":1,"iv":"oKGio6Slpqeoqaqr","ct":"2mhCZSCnbtBCA+6rcw+yu1DbNmL+035D7DA3Y3Mx+tYXjHwbXse5ATqs"}"""
    private val attachmentEnvelope = """{"nomaEnc":1,"iv":"sLGys7S1tre4ubq7","ct":"/TQuyta53icz1+fOrDTm+eZdOrcjGqNmGZjxkxu6lU9dGRNjNJDJ2vIN1S59hL+x1AKIWsPPgOi562BCgupl"}"""
    private val slotPasswordJson = """{"salt":"MDEyMzQ1Njc4OWFiY2RlZg==","iterations":600000,"wrappedKey":"wMHCw8TFxsfIycrLaQhOvIdzgivKBK7Ie/GBjs1iWSRbPZJ9pIcn7tAbwOG2ImXKaJ+oJ8G4TsIFrZUK"}"""
    private val slotPinJson = """{"salt":"ZmVkY2JhOTg3NjU0MzIxMA==","iterations":300000,"wrappedKey":"0NHS09TV1tfY2drbYRCFqcCv7U/R4ZfDOyszgbEGspc7Np+3DnjsKTTv2Et2v8L9fI/d3GoM7h5jUR6Z"}"""
    private val slotPatternJson = """{"salt":"cGF0dGVybi1zYWx0LTEyMw==","iterations":100000,"wrappedKey":"4OHi4+Tl5ufo6erri+CwbG9VLeFgz2OnBklAeToCTUiBMORiYo+45Pvv94HTaKCoPafw5J9KRzSyBbQN"}"""

    private fun slotFromJson(json: String): NoteLockSlot {
        fun field(name: String): String =
            Regex(""""$name"\s*:\s*"?([^",}]+)"?""").find(json)?.groupValues?.get(1)
                ?: error("field $name missing in $json")
        return NoteLockSlot(
            salt = field("salt"),
            iterations = field("iterations").toInt(),
            wrappedKey = field("wrappedKey"),
        )
    }

    // ------------------------------------------------ fixtures: unwrap

    @Test
    fun fixtureSlots_unwrapToFixtureNek_allThreeMethods() {
        assertArrayEquals(
            nek,
            NoteLockCrypto.unwrapNoteKey(
                slotFromJson(slotPasswordJson),
                NoteLockMethod.PASSWORD,
                NoteLockCrypto.canonicalPassword("correct horse fixture"),
            ),
        )
        assertArrayEquals(
            nek,
            NoteLockCrypto.unwrapNoteKey(
                slotFromJson(slotPinJson),
                NoteLockMethod.PIN,
                NoteLockCrypto.canonicalPin("135790"),
            ),
        )
        assertArrayEquals(
            nek,
            NoteLockCrypto.unwrapNoteKey(
                slotFromJson(slotPatternJson),
                NoteLockMethod.PATTERN,
                NoteLockCrypto.canonicalPattern(listOf(0, 1, 2, 5, 8)),
            ),
        )
    }

    @Test
    fun fixtureEnvelopes_decryptToFixturePlaintexts() {
        assertEquals(fixtureHtml, NoteLockCrypto.decryptText(nek, contentEnvelope))
        // The attachment payload plaintext is the DATA URL, not raw bytes.
        assertEquals(fixtureDataUrl, NoteLockCrypto.decryptText(nek, attachmentEnvelope))
        val parsed = NoteLockCrypto.parseDataUrl(fixtureDataUrl)
        assertEquals("text/plain", parsed?.first)
        assertEquals("Hello attachment", parsed?.second?.let { String(it, Charsets.UTF_8) })
    }

    @Test
    fun fixtureSlots_wrongSecretsReturnNull() {
        assertNull(
            NoteLockCrypto.unwrapNoteKey(
                slotFromJson(slotPinJson),
                NoteLockMethod.PIN,
                NoteLockCrypto.canonicalPin("135791"),
            ),
        )
        assertNull(
            NoteLockCrypto.unwrapNoteKey(
                slotFromJson(slotPatternJson),
                NoteLockMethod.PATTERN,
                NoteLockCrypto.canonicalPattern(listOf(0, 1, 2, 5)),
            ),
        )
    }

    // ------------------------------------------------ reverse direction

    /**
     * A Nota-produced slot + envelope, opened with RAW JCE written inline
     * here (no NoteLockCrypto calls on the opening side) — this proves
     * the FORMAT, not mere self-consistency.
     */
    @Test
    fun notaProducedSlotAndEnvelope_openWithRawJce() {
        val key = ByteArray(32) { (0x20 + it).toByte() }
        val canonical = "noma_pattern_v1:0-4-8"
        val slot = NoteLockCrypto.wrapNoteKey(
            key, NoteLockMethod.PATTERN, NoteLockCrypto.canonicalPattern(listOf(0, 4, 8)),
        )
        // Structural: wrappedKey decodes to iv(12) + ct(32) + tag(16) = 60.
        val packed = Base64.getDecoder().decode(slot.wrappedKey)
        assertEquals(60, packed.size)
        assertEquals(100_000, slot.iterations)

        // Raw PBKDF2 -> KEK.
        val salt = Base64.getDecoder().decode(slot.salt)
        assertEquals(16, salt.size)
        val spec = PBEKeySpec(canonical.toCharArray(), salt, slot.iterations, 256)
        val kek = SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256")
            .generateSecret(spec).encoded
        spec.clearPassword()
        // Raw AES-GCM open of iv||ct.
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(
            Cipher.DECRYPT_MODE,
            SecretKeySpec(kek, "AES"),
            GCMParameterSpec(128, packed.copyOfRange(0, 12)),
        )
        assertArrayEquals(key, cipher.doFinal(packed.copyOfRange(12, packed.size)))

        // Envelope: exact key order/set, opened raw.
        val envelope = NoteLockCrypto.encryptText(key, "reverse check")
        assertTrue(envelope.startsWith("{\"nomaEnc\":1,\"iv\":\""))
        assertTrue(envelope.indexOf("\"iv\"") < envelope.indexOf("\"ct\""))
        val iv = Base64.getDecoder().decode(
            Regex(""""iv":"([^"]+)"""").find(envelope)!!.groupValues[1],
        )
        val ct = Base64.getDecoder().decode(
            Regex(""""ct":"([^"]+)"""").find(envelope)!!.groupValues[1],
        )
        val open = Cipher.getInstance("AES/GCM/NoPadding")
        open.init(Cipher.DECRYPT_MODE, SecretKeySpec(key, "AES"), GCMParameterSpec(128, iv))
        assertEquals("reverse check", String(open.doFinal(ct), Charsets.UTF_8))
    }

    // ------------------------------------------------ envelope basics

    @Test
    fun isEncryptedContent_truthTable() {
        assertTrue(NoteLockCrypto.isEncryptedContent(contentEnvelope))
        assertFalse(NoteLockCrypto.isEncryptedContent(""))
        assertFalse(NoteLockCrypto.isEncryptedContent("plain text"))
        assertFalse(NoteLockCrypto.isEncryptedContent("{\"nomaEnc\":1"))
        assertFalse(NoteLockCrypto.isEncryptedContent("{\"nomaEnc\":2,\"iv\":\"x\",\"ct\":\"y\"}"))
        assertFalse(NoteLockCrypto.isEncryptedContent("{\"nomaEnc\":1,\"iv\":\"\",\"ct\":\"y\"}"))
        assertFalse(NoteLockCrypto.isEncryptedContent("{\"nomaEnc\":1,\"ct\":\"y\"}"))
        // 1.x checks field TYPES only (any non-empty strings pass).
        assertTrue(NoteLockCrypto.isEncryptedContent("{\"nomaEnc\":1,\"iv\":\"x\",\"ct\":\"y\"}"))
    }

    @Test
    fun envelopeRoundTrip_randomKeysAndPacking() {
        val key = NoteLockCrypto.generateNoteKey()
        assertEquals(32, key.size)
        val envelope = NoteLockCrypto.encryptText(key, "<p>round trip</p>")
        assertTrue(NoteLockCrypto.isEncryptedContent(envelope))
        assertEquals("<p>round trip</p>", NoteLockCrypto.decryptText(key, envelope))
        // Packed form (slot/biometric shape) rebuilds an equivalent envelope.
        val packed = NoteLockCrypto.packEnvelope(envelope)!!
        assertEquals(12 + 16 + "<p>round trip</p>".toByteArray().size, Base64.getDecoder().decode(packed).size)
        val rebuilt = NoteLockCrypto.envelopeFromPacked(packed)!!
        assertEquals("<p>round trip</p>", NoteLockCrypto.decryptText(key, rebuilt))
        assertNull(NoteLockCrypto.envelopeFromPacked("!!!not-base64!!!"))
    }

    @Test
    fun dataUrl_buildParseRoundTrip() {
        val bytes = byteArrayOf(1, 2, 3, 250.toByte())
        val url = NoteLockCrypto.buildDataUrl("image/png", bytes)
        assertTrue(url.startsWith("data:image/png;base64,"))
        val parsed = NoteLockCrypto.parseDataUrl(url)!!
        assertEquals("image/png", parsed.first)
        assertArrayEquals(bytes, parsed.second)
        assertNull(NoteLockCrypto.parseDataUrl("https://example.com/x"))
        assertNull(NoteLockCrypto.parseDataUrl("data:text/plain,hello"))
    }

    @Test
    fun canonicalFormsAndValidation_match1x() {
        assertEquals("noma_pin_v1:135790", NoteLockCrypto.canonicalPin("135790"))
        assertEquals(
            "noma_pattern_v1:0-1-2-5-8",
            NoteLockCrypto.canonicalPattern(listOf(0, 1, 2, 5, 8)),
        )
        assertTrue(NoteLockCrypto.isValidPin("135790"))
        assertFalse(NoteLockCrypto.isValidPin("135"))
        assertFalse(NoteLockCrypto.isValidPin("1357901"))
        assertTrue(
            NoteLockCrypto.isValidCanonicalSecret(
                NoteLockMethod.PASSWORD, NoteLockCrypto.canonicalPassword("correct horse fixture"),
            ),
        )
        assertFalse(
            NoteLockCrypto.isValidCanonicalSecret(
                NoteLockMethod.PASSWORD, NoteLockCrypto.canonicalPassword("short"),
            ),
        )
        assertTrue(
            NoteLockCrypto.isValidCanonicalSecret(
                NoteLockMethod.PATTERN, NoteLockCrypto.canonicalPattern(listOf(0, 1, 2, 5)),
            ),
        )
        assertFalse(
            NoteLockCrypto.isValidCanonicalSecret(
                NoteLockMethod.PATTERN, NoteLockCrypto.canonicalPattern(listOf(0, 1, 2)),
            ),
        )
    }
}
